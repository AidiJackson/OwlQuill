# ── authorisation still enforced on top of authentication ───────────────────


def test_admin_route_enforced(client: TestClient):
    user_token = get_auth_token(client, email="plain@test.com", username="plainuser")
    admin_token = get_auth_token(client, email="boss@test.com", username="bossuser")
    make_admin("boss@test.com")

    assert client.get("/admin/reports", headers=auth_headers("garbage")).status_code == 401
    assert client.get("/admin/reports", headers=auth_headers(user_token)).status_code == 403
    assert client.get("/admin/reports", headers=auth_headers(admin_token)).status_code == 200


def test_character_ownership_enforced(client: TestClient):
    owner_token = get_auth_token(client, email="owner@test.com", username="owneruser")
    other_token = get_auth_token(client, email="other@test.com", username="otheruser")
    character_id = ensure_character(client, owner_token)

    patch = {"name": "Renamed"}
    url = f"/characters/{character_id}"
    assert client.patch(url, json=patch, headers=auth_headers("garbage")).status_code == 401
    assert client.patch(url, json=patch, headers=auth_headers(other_token)).status_code == 403
    assert client.delete(url, headers=auth_headers(other_token)).status_code == 403
    assert client.patch(url, json=patch, headers=auth_headers(owner_token)).status_code == 200
