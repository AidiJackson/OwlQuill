"""JWT compatibility pins for the python-jose → PyJWT replacement.

Replit's package firewall blocks every python-jose release ("Critical CVE"), so
``app.core.security`` now uses PyJWT. Sessions already issued by production were
signed by python-jose and must keep working after the swap — a mismatch would
log every user out at once.

The ``LEGACY_*`` tokens below are NOT generated by PyJWT. They were produced by
python-jose 3.4.0 — the exact build in the last successful production deploy
(``.deploy-python``) — with the suite's test secret and HS256, ``exp`` passed as
a ``datetime`` exactly as ``create_access_token`` does:

    jose.jwt.encode({"sub": "1", "exp": datetime(2099, 1, 1)},
                    "test-secret-key-not-for-prod", algorithm="HS256")

Do not regenerate them with PyJWT; that would make the compatibility test
circular.
"""
import base64
import json
import time
from datetime import timedelta

import jwt
import pytest
from fastapi.testclient import TestClient

from app.core.security import create_access_token, decode_access_token
from tests.conftest import auth_headers, ensure_character, get_auth_token, make_admin

TEST_SECRET = "test-secret-key-not-for-prod"

# python-jose 3.4.0, {"sub": "1", "exp": 2099-01-01T00:00:00Z}
LEGACY_VALID = (
    "eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9."
    "eyJzdWIiOiIxIiwiZXhwIjo0MDcwOTA4ODAwfQ."
    "9MQIkiiGXQXc91r2eaxD96zcYheCpW0L7ohITgzytlU"
)
# python-jose 3.4.0, {"sub": "1", "exp": 2020-01-01T00:00:00Z}
LEGACY_EXPIRED = (
    "eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9."
    "eyJzdWIiOiIxIiwiZXhwIjoxNTc3ODM2ODAwfQ."
    "EtGy3GMQbobj81L8IG2AgQSgBVK5_PX6hAIi1vGttYg"
)
# python-jose 3.4.0, {"exp": 2099-01-01T00:00:00Z} — no sub
LEGACY_NO_SUB = (
    "eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9."
    "eyJleHAiOjQwNzA5MDg4MDB9."
    "6sHHldr_fr8Hbv0tYc5IcMjJ7yMhJuC_l6u_vkeqfhM"
)


def _b64(obj) -> str:
    raw = obj if isinstance(obj, bytes) else json.dumps(obj, separators=(",", ":")).encode()
    return base64.urlsafe_b64encode(raw).rstrip(b"=").decode()


def _segments(token: str) -> tuple[dict, dict]:
    head, body, _ = token.split(".")
    pad = lambda s: s + "=" * (-len(s) % 4)  # noqa: E731
    return (
        json.loads(base64.urlsafe_b64decode(pad(head))),
        json.loads(base64.urlsafe_b64decode(pad(body))),
    )


def _register_first_user(client: TestClient) -> str:
    """Register the first account in the fresh test DB (id 1, matching the
    legacy fixtures' ``sub``) and return its own token."""
    token = get_auth_token(client, email="legacy@test.com", username="legacyuser")
    me = client.get("/auth/me", headers=auth_headers(token))
    assert me.status_code == 200
    assert me.json()["id"] == 1, "legacy fixtures assume the first user is id 1"
    return token


def _assert_401(client: TestClient, token: str) -> None:
    resp = client.get("/auth/me", headers=auth_headers(token))
    assert resp.status_code == 401, (token, resp.status_code, resp.text)


# ── legacy (python-jose-issued) tokens ───────────────────────────────────────


def test_legacy_jose_token_decodes_to_identical_claims():
    assert decode_access_token(LEGACY_VALID) == {"sub": "1", "exp": 4070908800}


def test_legacy_jose_token_authenticates_existing_session(client: TestClient):
    _register_first_user(client)
    resp = client.get("/auth/me", headers=auth_headers(LEGACY_VALID))
    assert resp.status_code == 200
    assert resp.json()["email"] == "legacy@test.com"


def test_legacy_jose_expired_token_rejected(client: TestClient):
    _register_first_user(client)
    assert decode_access_token(LEGACY_EXPIRED) is None
    _assert_401(client, LEGACY_EXPIRED)


def test_legacy_jose_token_without_sub_rejected(client: TestClient):
    _register_first_user(client)
    _assert_401(client, LEGACY_NO_SUB)


# ── tokens issued after the swap keep the legacy shape ───────────────────────


def test_new_token_header_and_claims_match_legacy_format():
    before = int(time.time())
    token = create_access_token(data={"sub": "42"})
    header, payload = _segments(token)
    legacy_header, _ = _segments(LEGACY_VALID)

    assert header == legacy_header == {"alg": "HS256", "typ": "JWT"}
    assert set(payload) == {"sub", "exp"}
    assert payload["sub"] == "42"
    assert isinstance(payload["exp"], int)
    week = 7 * 24 * 60 * 60
    assert before + week - 5 <= payload["exp"] <= int(time.time()) + week + 5


def test_login_issues_valid_token_accepted_by_protected_route(client: TestClient):
    token = get_auth_token(client)
    _, payload = _segments(token)
    assert set(payload) == {"sub", "exp"}
    resp = client.get("/auth/me", headers=auth_headers(token))
    assert resp.status_code == 200
    assert str(resp.json()["id"]) == payload["sub"]


def test_freshly_expired_token_rejected(client: TestClient):
    _register_first_user(client)
    token = create_access_token(data={"sub": "1"}, expires_delta=timedelta(seconds=-1))
    _assert_401(client, token)


# ── forged / malformed tokens: always 401, never 500 ─────────────────────────


def test_wrong_secret_rejected(client: TestClient):
    _register_first_user(client)
    forged = jwt.encode({"sub": "1", "exp": 4070908800}, "not-the-secret", algorithm="HS256")
    _assert_401(client, forged)


def test_tampered_payload_rejected(client: TestClient):
    _register_first_user(client)
    get_auth_token(client, email="victim@test.com", username="victim")  # id 2
    head, _, sig = LEGACY_VALID.split(".")
    tampered = f"{head}.{_b64({'sub': '2', 'exp': 4070908800})}.{sig}"
    _assert_401(client, tampered)


def test_tampered_signature_rejected(client: TestClient):
    _register_first_user(client)
    head, body, sig = LEGACY_VALID.split(".")
    flipped = ("A" if sig[0] != "A" else "B") + sig[1:]
    _assert_401(client, f"{head}.{body}.{flipped}")


@pytest.mark.parametrize(
    "token",
    [
        "garbage",
        "a.b",
        "a.b.c",
        "a.b.c.d",
        "!!!.!!!.!!!",
        f"{_b64(b'not json')}.{_b64({'sub': '1'})}.sig",
        f"{_b64({'alg': 'HS256', 'typ': 'JWT'})}.{_b64(b'not json')}.sig",
        f"{_b64({'alg': 'HS256', 'typ': 'JWT'})}.{_b64([1, 2, 3])}.sig",
        f"{_b64([1])}.{_b64({'sub': '1'})}.sig",
    ],
)
def test_malformed_tokens_return_401_not_500(client: TestClient, token: str):
    _register_first_user(client)
    _assert_401(client, token)


@pytest.mark.parametrize("exp", ['"soon"', "null", "1e400", "[1]", '{"a":1}'])
def test_malformed_exp_returns_401_not_500(client: TestClient, exp: str):
    """Correctly signed, but ``exp`` is not a usable timestamp."""
    _register_first_user(client)
    payload = f'{{"sub":"1","exp":{exp}}}'.encode()
    token = jwt.api_jws.encode(payload, TEST_SECRET, algorithm="HS256")
    _assert_401(client, token)


def test_alg_none_rejected(client: TestClient):
    _register_first_user(client)
    unsigned = f"{_b64({'alg': 'none', 'typ': 'JWT'})}.{_b64({'sub': '1', 'exp': 4070908800})}."
    _assert_401(client, unsigned)


def test_unsupported_algorithm_with_correct_secret_rejected(client: TestClient):
    _register_first_user(client)
    hs512 = jwt.encode({"sub": "1", "exp": 4070908800}, TEST_SECRET, algorithm="HS512")
    _assert_401(client, hs512)


