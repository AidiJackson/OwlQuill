@router.post("/chapters/generate", response_model=ChapterGenerateResponse, dependencies=[Depends(require_creator)])
def generate_chapter_endpoint(
    story_id: str = Query(..., description="Story workspace identifier"),
    req: ChapterGenerateRequest = ...,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user),
) -> ChapterGenerateResponse:
    """Generate a new chapter and store it."""
    _validate_story_ownership(story_id, current_user, db)
    # S24D FIX 3: non-SFW boundaries are admin-only during launch.
    _require_admin_for_boundary(req.controls.boundary, current_user)
    storylab_telemetry.reset()

    import time as _time
    _endpoint_t0 = _time.time()

    user_key = str(current_user.id)
    limit = settings.STORYLAB_DAILY_LIMIT
    if limit > 0:
        used = _count_daily_chapters_for_user(user_key, db)
        if used >= limit:
            raise _storylab_quota_error(used, limit)

    logger.info(
        "[SL-PATH] generate_chapter_endpoint | story_id=%s length=%s pacing=%s "
        "tone=%s boundary=%s direction=%s mode=%s provider=%s model=%s",
        story_id,
        req.controls.length, req.controls.pacing, req.controls.tone_intensity,
        req.controls.boundary, req.controls.direction, req.mode,
        settings.STORYLAB_PROVIDER, settings.STORYLAB_MODEL,
    )

    # Capture pre-generation canon memory for contradiction checking.
    # For first chapters this will be empty; the seeded memory is returned
    # by _run_chapter_generation as its 4th element and used as fallback.
    _pre_state = _get_or_create_state(story_id, db)
    _pre_memory: dict[str, Any] = (_pre_state.state_json or {}).get("memory") or {}
    # Snapshot pre-generation state_json so we can restore it before any retry,
    # preventing double state-delta application for a single saved chapter.
    _pre_state_json_snapshot: dict[str, Any] = dict(_pre_state.state_json or {})

    try:
        chapter_text, suggestions, model_deltas, _post_memory = _run_chapter_generation(story_id, req, db)
    except HTTPException:
        raise
    except Exception as exc:
        logger.error("StoryLab chapter generation failed for %s: %s", story_id, exc)
        raise HTTPException(
            status_code=502,
            detail={
                "error": "storylab_failed",
                "detail": "Story generation failed. Please try again.",
                "hint": "Check OPENROUTER_API_KEY or try again shortly.",
                "provider": settings.STORYLAB_PROVIDER,
                "model": get_effective_story_model(),
            },
        ) from exc

    if not chapter_text.strip():
        logger.error("StoryLab chapter generation returned empty text for story %s", story_id)
        raise HTTPException(
            status_code=502,
            detail={
                "error": "empty_generation",
                "detail": "Generation produced no text. Please try again.",
                "hint": "The model may have returned an unusable response.",
            },
        )

    word_count = len(chapter_text.split())
    chapter_number = _get_next_chapter_number(story_id, db)

    # ── Blocking canon contradiction check — BEFORE db.commit() ───────────────
    # Use pre-memory when available (chapters 2+); fall back to the seeded
    # post-memory for chapter 1 (where pre-memory is empty before seeding).
    _check_memory = _pre_memory or _post_memory
    if _check_memory:
        contradictions = check_for_contradictions(chapter_text, _check_memory)
        if contradictions:
            logger.warning(
                "[STORY-CANON-BLOCKED] story_id=%s chapter=%d violations=%d"
                " detected_phrases=%s — triggering retry (attempt 2/2).",
                story_id, chapter_number, len(contradictions), contradictions,
            )
            correction_note = _build_canon_correction_note(contradictions, _check_memory)
            try:
                # Restore pre-generation state before retry to prevent double
                # state-delta application for a single chapter.
                _pre_state.state_json = _pre_state_json_snapshot
                db.add(_pre_state)
                logger.info(
                    "[STORY-CANON-RETRY] story_id=%s chapter=%d attempt=2/2.",
                    story_id, chapter_number,
                )
                chapter_text, suggestions, model_deltas, _post_memory = _run_chapter_generation(
                    story_id, req, db, canon_correction_note=correction_note
                )
                retry_contradictions = check_for_contradictions(chapter_text, _check_memory)
                if retry_contradictions:
                    logger.error(
                        "[STORY-CANON-BLOCKED] story_id=%s chapter=%d retry_also_violated=%d"
                        " — refusing to save. violations=%s",
                        story_id, chapter_number, len(retry_contradictions), retry_contradictions,
                    )
                    raise HTTPException(
                        status_code=422,
                        detail={
                            "error": "canon_contradiction",
                            "detail": (
                                "Generated chapter contradicts hard canon and could not be "
                                "corrected automatically. Please adjust your prompt and try again."
                            ),
                            "contradictions": retry_contradictions,
                        },
                    )
                logger.info(
                    "[STORY-CANON-RETRY] story_id=%s chapter=%d retry_succeeded.",
                    story_id, chapter_number,
                )
                word_count = len(chapter_text.split())
            except HTTPException:
                raise
            except Exception as retry_exc:
                logger.error(
                    "[STORY-CANON-BLOCKED] story_id=%s chapter=%d retry_generation_failed: %s"
                    " — refusing to save.",
                    story_id, chapter_number, retry_exc,
                )
                raise HTTPException(
                    status_code=422,
                    detail={
                        "error": "canon_contradiction",
                        "detail": (
                            "Generated chapter contradicts hard canon. "
                            "The correction attempt also failed. Please try again."
                        ),
                        "contradictions": contradictions,
                    },
                ) from retry_exc

    controls_snapshot = {
        "direction": req.controls.direction,
        "tone_intensity": req.controls.tone_intensity,
        "pacing": req.controls.pacing,
        "length": req.controls.length,
        "boundary": req.controls.boundary,
    }
    now = datetime.utcnow()
    ch = StoryChapter(
        story_id=story_id,
        user_id=user_key,
        chapter_number=chapter_number,
        prompt_text=req.prompt or "",
        mode=req.mode,
        controls_json=controls_snapshot,
        generated_text=chapter_text,
        word_count=word_count,
        created_at=now,
        updated_at=now,
    )
    db.add(ch)
    db.commit()
    db.refresh(ch)

    # Update story summary + character memory (both non-fatal; chapter already committed)
    # S24AZ T3: summary is batched to cut per-chapter cost ~20–25%. It fires on
    # the first chapter (so early chapters have summary context) and then only
    # every 3rd chapter thereafter, instead of after every single chapter.
    state_row = _get_or_create_state(story_id, db)
    if chapter_number == 1 or chapter_number % 3 == 0:
        _update_story_summary(story_id, state_row, chapter_text, chapter_number, db)
        state_row = _get_or_create_state(story_id, db)  # re-fetch after summary commit
    _update_character_memory(story_id, user_key, state_row, db)

    # ── Canon memory extraction + contradiction check (non-fatal) ─────────────
    _update_canon_memory(story_id, chapter_text, chapter_number, state_row, db)

    # ── telemetry: chapter gen + (optional) summary + canon_extract ───────────
    _persist_generation_telemetry(
        db, user_id=current_user.id, story_id=story_id, request_id=None
    )

    _endpoint_ms = int((_time.time() - _endpoint_t0) * 1000)
    _using_stub = chapter_text.startswith("[DEV-STUB-FALLBACK]") or (model_deltas is None and settings.STORYLAB_PROVIDER == "stub")
    logger.info(
        "[SL-PATH] generate_chapter_endpoint COMPLETE | story_id=%s chapter=%d "
        "word_count=%d endpoint_ms=%d using_stub=%s",
        story_id, chapter_number, word_count, _endpoint_ms, _using_stub,
    )
    if _endpoint_ms < 1500 and settings.STORYLAB_PROVIDER == "openrouter":
        logger.warning(
            "[SL-PATH] SUSPICIOUS: endpoint completed in %dms with provider=openrouter — "
            "possible silent fallback to stub. Check SL-DIAG logs above for fallback_reason.",
            _endpoint_ms,
        )

    return ChapterGenerateResponse(
        chapter_number=chapter_number,
        generated_text=chapter_text,
        prompt_text=req.prompt or "",
        suggestions=suggestions,
        meta={
            "words": word_count,
            "delta": model_deltas,
            "story_model": get_effective_story_model(),
            "diag": {
                "provider": settings.STORYLAB_PROVIDER,
                "model": get_effective_story_model(),
                "endpoint_ms": _endpoint_ms,
                "length": req.controls.length,
                "pacing": req.controls.pacing,
                "tone": req.controls.tone_intensity,
                "using_stub": _using_stub,
            },
        },
    )


