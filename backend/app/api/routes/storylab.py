def _build_story_context(
    story_id: str,
    db: Session,
) -> tuple[str, str, str, str, list[dict[str, Any]]]:
    """Fetch story identity, realm description, and character dicts for generation.

    Returns (title, genre, premise, realm_description, story_characters).
    All fields gracefully degrade to empty strings / empty list when data is absent.
    """
    story_obj = db.query(StoryModel).filter(StoryModel.id == story_id).first()
    if not story_obj:
        return "", "", "", "", []

    title = story_obj.title or ""
    genre = story_obj.genre or ""
    premise = story_obj.premise or ""

    # Realm description
    realm_description = ""
    if story_obj.realm_id:
        realm_obj = db.query(Realm).filter(Realm.id == story_obj.realm_id).first()
        if realm_obj:
            parts = [p for p in (realm_obj.name, realm_obj.tagline, realm_obj.description) if p]
            realm_description = " — ".join(parts)

    # Story-bound characters
    story_characters: list[dict[str, Any]] = []
    char_ids = story_obj.character_ids or []
    if char_ids:
        char_rows = (
            db.query(CharacterModel)
            .filter(CharacterModel.id.in_(char_ids))
            .all()
        )
        for c in char_rows:
            entry: dict[str, Any] = {
                "name": c.name or "Unknown",
                "role": c.role or "",
                "short_bio": c.short_bio or "",
                # Additional identity fields for richer protagonist anchor
                "age": c.age or "",
                "species": c.species or "",
                "era": c.era or "",
                "tags": c.tags or "",  # comma-separated trait tags
            }
            # Merge identity_spec_json voice/behaviour fields for richer prompt injection
            if c.identity_spec_json:
                try:
                    spec = (
                        json.loads(c.identity_spec_json)
                        if isinstance(c.identity_spec_json, str)
                        else c.identity_spec_json
                    )
                    if isinstance(spec, dict):
                        for field in (
                            "personality", "traits", "voice", "speech_style", "tone",
                            "motivation", "behavior", "pursuit_style", "never",
                            "power_style", "emotional_pacing",
                        ):
                            val = spec.get(field)
                            if val:
                                entry[field] = val
                except (json.JSONDecodeError, TypeError, AttributeError):
                    pass
            story_characters.append(entry)

    return title, genre, premise, realm_description, story_characters


def _run_chapter_generation(
    story_id: str,
    req: ChapterGenerateRequest,
    db: Session,
    canon_correction_note: str = "",
) -> tuple[str, list[str], dict[str, Any] | None]:
    """Shared generation logic: fetch state, get previous chapter, call generator.

    canon_correction_note — when non-empty, prepended to the user prompt so the
    model is given explicit guidance to correct a prior canon contradiction.
    """
    state_row = _get_or_create_state(story_id, db)
    current_state: dict[str, Any] = dict(state_row.state_json or _DEFAULT_STATE)

    # Last chapter text for continuity context
    last_chapter = (
        db.query(StoryChapter)
        .filter(StoryChapter.story_id == story_id)
        .order_by(StoryChapter.chapter_number.desc())
        .first()
    )
    previous_text = last_chapter.generated_text if last_chapter else None

    # Story-bound context enrichment (gracefully degrades when story/realm/chars absent)
    story_title, story_genre, story_premise, realm_description, story_characters = (
        _build_story_context(story_id, db)
    )

    # ── Load or seed canon memory ─────────────────────────────────────────────
    canon_memory: dict[str, Any] = current_state.get("memory") or {}
    is_first_chapter = last_chapter is None
    if is_first_chapter and not _has_memory_content(canon_memory):
        # Seed memory from story creation inputs on the first chapter
        canon_memory = seed_memory_from_story_creation(
            title=story_title,
            genre=story_genre,
            premise=story_premise,
            characters=story_characters,
        )
        current_state["memory"] = canon_memory

    logger.info(
        "[STORY-MEMORY] loaded | story_id=%s hard_truths=%d characters=%d "
        "relationships=%d open_threads=%d",
        story_id,
        len((canon_memory.get("canon") or {}).get("hard_truths", [])),
        len(canon_memory.get("characters") or {}),
        len(canon_memory.get("relationships") or []),
        len(canon_memory.get("open_threads") or []),
    )

    effective_prompt = req.prompt or ""
    if canon_correction_note:
        effective_prompt = (canon_correction_note + "\n\n" + effective_prompt).strip()

    chapter_text, suggestions, model_deltas = generate_chapter(
        prompt=effective_prompt,
        controls=req.controls,
        state_json=current_state,
        summary=state_row.story_summary or "",
        characters=current_state.get("characters", []),
        previous_chapter_text=previous_text,
        story_id=story_id,
        variant=req.variant,
        story_title=story_title,
        story_genre=story_genre,
        story_premise=story_premise,
        realm_description=realm_description,
        story_characters=story_characters,
        beat_type=req.beat_type,
        canon_memory=canon_memory or None,
    )

    # Update story state (preserve memory key through the delta update)
    new_state, _ = _build_deltas(req.controls.direction, req.controls.boundary, current_state)
    if model_deltas:
        new_state = apply_model_deltas(new_state, model_deltas, req.controls.boundary)
    # Carry forward the canon memory into the new state
    new_state["memory"] = canon_memory
    state_row.state_json = new_state
    state_row.updated_at = datetime.utcnow()
    db.add(state_row)

    return chapter_text, suggestions, model_deltas, canon_memory


def _has_memory_content(memory: dict[str, Any]) -> bool:
    """Return True if the memory dict has any substantive content."""
    if not memory or not isinstance(memory, dict):
        return False
    return bool(
        (memory.get("canon") or {}).get("hard_truths")
        or memory.get("characters")
        or memory.get("open_threads")
    )


def _update_story_summary(
    story_id: str,
    state_row: StoryState,
    chapter_text: str,
    chapter_number: int,
    db: Session,
) -> None:
    """Generate and persist an updated story summary after a chapter is saved.

    Non-fatal: if summarisation fails the chapter is already committed and the
    summary will be regenerated on the next chapter generation.
    """
    try:
        new_summary = generate_story_summary(
            existing_summary=state_row.story_summary or "",
            chapter_text=chapter_text,
            chapter_number=chapter_number,
            story_id=story_id,
        )
        state_row.story_summary = new_summary
        state_row.updated_at = datetime.utcnow()
        db.add(state_row)
        db.commit()
    except Exception as exc:  # noqa: BLE001
        logger.warning("Story summary update failed for %s: %s", story_id, exc)


