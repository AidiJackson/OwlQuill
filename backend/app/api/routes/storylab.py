@router.post("/chapters/generate", response_model=ChapterGenerateResponse)
def generate_chapter_endpoint(
    story_id: str = Query(..., description="Story workspace identifier"),
    req: ChapterGenerateRequest = ...,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user),
) -> ChapterGenerateResponse:
    """Generate a new chapter and store it."""
    user_key = str(current_user.id)
    limit = settings.STORYLAB_DAILY_LIMIT
    if limit > 0:
        used = _count_daily_chapters_for_user(user_key, db)
        if used >= limit:
            raise _storylab_quota_error(used, limit)

    # Capture pre-generation canon memory for contradiction checking.
    # For first chapters this will be empty; the seeded memory is returned
    # by _run_chapter_generation as its 4th element and used as fallback.
    _pre_state = _get_or_create_state(story_id, db)
    _pre_memory: dict[str, Any] = (_pre_state.state_json or {}).get("memory") or {}

    try:
        chapter_text, suggestions, model_deltas, _post_memory = _run_chapter_generation(story_id, req, db)
    except HTTPException:
        raise
    except Exception as exc:
        logger.error("StoryLab chapter generation failed for %s: %s", story_id, exc)
        raise HTTPException(
            status_code=502,
            detail={
                "error": "storylab_failed",
                "detail": "Story generation failed. Please try again.",
                "hint": "Check OPENROUTER_API_KEY or try again shortly.",
                "provider": settings.STORYLAB_PROVIDER,
                "model": settings.STORYLAB_MODEL,
            },
        ) from exc

    if not chapter_text.strip():
        logger.error("StoryLab chapter generation returned empty text for story %s", story_id)
        raise HTTPException(
            status_code=502,
            detail={
                "error": "empty_generation",
                "detail": "Generation produced no text. Please try again.",
                "hint": "The model may have returned an unusable response.",
            },
        )

    word_count = len(chapter_text.split())
    chapter_number = _get_next_chapter_number(story_id, db)

    # ── Blocking canon contradiction check — BEFORE db.commit() ───────────────
    # Use pre-memory when available (chapters 2+); fall back to the seeded
    # post-memory for chapter 1 (where pre-memory is empty before seeding).
    _check_memory = _pre_memory or _post_memory
    if _check_memory:
        contradictions = check_for_contradictions(chapter_text, _check_memory)
        if contradictions:
            logger.warning(
                "[STORY-CANON-AUDIT] story_id=%s chapter=%d contradictions_found=%d "
                "— attempting correction retry. details=%s",
                story_id, chapter_number, len(contradictions), contradictions,
            )
            correction_note = (
                "CANON CORRECTION REQUIRED: The previous generation attempt violated hard canon. "
                "Specifically: " + "; ".join(contradictions[:3]) + ". "
                "Regenerate this chapter without these violations. "
                "All characters confirmed alive in canon must remain alive in this chapter."
            )
            try:
                chapter_text, suggestions, model_deltas, _post_memory = _run_chapter_generation(
                    story_id, req, db, canon_correction_note=correction_note
                )
                retry_contradictions = check_for_contradictions(chapter_text, _check_memory)
                if retry_contradictions:
                    logger.error(
                        "[STORY-CANON-AUDIT] story_id=%s chapter=%d retry_also_violated=%d "
                        "— refusing to save chapter. details=%s",
                        story_id, chapter_number, len(retry_contradictions), retry_contradictions,
                    )
                    raise HTTPException(
                        status_code=422,
                        detail={
                            "error": "canon_contradiction",
                            "detail": (
                                "Generated chapter contradicts hard canon and could not be "
                                "corrected automatically. Please adjust your prompt and try again."
                            ),
                            "contradictions": retry_contradictions,
                        },
                    )
                logger.info(
                    "[STORY-CANON-AUDIT] story_id=%s chapter=%d correction_retry_succeeded.",
                    story_id, chapter_number,
                )
                word_count = len(chapter_text.split())
            except HTTPException:
                raise
            except Exception as retry_exc:
                logger.error(
                    "[STORY-CANON-AUDIT] story_id=%s chapter=%d retry_generation_failed: %s "
                    "— refusing to save contradictory chapter.",
                    story_id, chapter_number, retry_exc,
                )
                raise HTTPException(
                    status_code=422,
                    detail={
                        "error": "canon_contradiction",
                        "detail": (
                            "Generated chapter contradicts hard canon. "
                            "The correction attempt also failed. Please try again."
                        ),
                        "contradictions": contradictions,
                    },
                ) from retry_exc

    controls_snapshot = {
        "direction": req.controls.direction,
        "tone_intensity": req.controls.tone_intensity,
        "pacing": req.controls.pacing,
        "length": req.controls.length,
        "boundary": req.controls.boundary,
    }
    now = datetime.utcnow()
    ch = StoryChapter(
        story_id=story_id,
        user_id=user_key,
        chapter_number=chapter_number,
        prompt_text=req.prompt or "",
        mode=req.mode,
        controls_json=controls_snapshot,
        generated_text=chapter_text,
        word_count=word_count,
        created_at=now,
        updated_at=now,
    )
    db.add(ch)
    db.commit()
    db.refresh(ch)

    # Update story summary + character memory (both non-fatal; chapter already committed)
    state_row = _get_or_create_state(story_id, db)
    _update_story_summary(story_id, state_row, chapter_text, chapter_number, db)
    state_row = _get_or_create_state(story_id, db)  # re-fetch after summary commit
    _update_character_memory(story_id, user_key, state_row, db)

    # ── Canon memory extraction + contradiction check (non-fatal) ─────────────
    _update_canon_memory(story_id, chapter_text, chapter_number, state_row, db)

    return ChapterGenerateResponse(
        chapter_number=chapter_number,
        generated_text=chapter_text,
        prompt_text=req.prompt or "",
        suggestions=suggestions,
        meta={"words": word_count, "delta": model_deltas},
    )


@router.delete("/chapters/{chapter_number}", status_code=204)
def delete_chapter(
    chapter_number: int,
    story_id: str = Query(..., description="Story workspace identifier"),
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user),
) -> None:
    """Delete a chapter. Gaps in chapter_number are preserved (no renumbering)."""
    ch = (
        db.query(StoryChapter)
        .filter(
            StoryChapter.story_id == story_id,
            StoryChapter.chapter_number == chapter_number,
        )
        .first()
    )
    if ch is None:
        raise HTTPException(status_code=404, detail="Chapter not found")
    # Ownership check: only the chapter author or an admin may delete.
    # ch.user_id may be empty for legacy rows (pre-auth); those are deletable by any authed user.
    is_admin = bool(current_user.is_admin) or current_user.email.lower() in settings.get_admin_emails()
    if ch.user_id and ch.user_id != str(current_user.id) and not is_admin:
        raise HTTPException(status_code=403, detail="Not your chapter")
    db.delete(ch)
    db.commit()


@router.post("/chapters/{chapter_number}/regenerate", response_model=ChapterGenerateResponse)
def regenerate_chapter(
    chapter_number: int,
    story_id: str = Query(..., description="Story workspace identifier"),
    req: ChapterGenerateRequest = ...,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user),
) -> ChapterGenerateResponse:
    """Regenerate a chapter in-place, overwriting its generated_text."""
    ch = (
        db.query(StoryChapter)
        .filter(
            StoryChapter.story_id == story_id,
            StoryChapter.chapter_number == chapter_number,
        )
        .first()
    )
    if ch is None:
        raise HTTPException(status_code=404, detail="Chapter not found")

    user_key = str(current_user.id)
    limit = settings.STORYLAB_DAILY_LIMIT
    if limit > 0:
        used = _count_daily_chapters_for_user(user_key, db)
        if used >= limit:
            raise _storylab_quota_error(used, limit)

    try:
        chapter_text, suggestions, model_deltas, _post_memory = _run_chapter_generation(story_id, req, db)
    except HTTPException:
        raise
    except Exception as exc:
        logger.error("StoryLab chapter regeneration failed for %s ch%s: %s", story_id, chapter_number, exc)
        raise HTTPException(
            status_code=502,
            detail={
                "error": "storylab_failed",
                "detail": "Story generation failed. Please try again.",
                "hint": "Check OPENROUTER_API_KEY or try again shortly.",
                "provider": settings.STORYLAB_PROVIDER,
                "model": settings.STORYLAB_MODEL,
            },
        ) from exc

    if not chapter_text.strip():
        logger.error("StoryLab chapter regeneration returned empty text for story %s ch%s", story_id, chapter_number)
        raise HTTPException(
            status_code=502,
            detail={
                "error": "empty_generation",
                "detail": "Generation produced no text. Please try again.",
                "hint": "The model may have returned an unusable response.",
            },
        )

    word_count = len(chapter_text.split())

    controls_snapshot = {
        "direction": req.controls.direction,
        "tone_intensity": req.controls.tone_intensity,
        "pacing": req.controls.pacing,
        "length": req.controls.length,
        "boundary": req.controls.boundary,
    }
    ch.generated_text = chapter_text
    ch.word_count = word_count
    ch.prompt_text = req.prompt or ch.prompt_text
    ch.controls_json = controls_snapshot
    ch.updated_at = datetime.utcnow()
    db.add(ch)
    db.commit()

    # Update story summary + character memory (both non-fatal; chapter already committed)
    state_row = _get_or_create_state(story_id, db)
    _update_story_summary(story_id, state_row, chapter_text, chapter_number, db)
    state_row = _get_or_create_state(story_id, db)  # re-fetch after summary commit
    _update_character_memory(story_id, user_key, state_row, db)

    return ChapterGenerateResponse(
        chapter_number=chapter_number,
        generated_text=chapter_text,
        prompt_text=req.prompt or ch.prompt_text or "",
        suggestions=suggestions,
        meta={"words": word_count, "delta": model_deltas},
    )


