@router.post("/stories", response_model=StoryResponse, status_code=201, dependencies=[Depends(require_creator)])
def create_story(
    req: StoryCreateRequest,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user),
) -> StoryResponse:
    """Create a new Story record with title, genre, premise, and optional realm/cast."""
    # Cap character list
    char_ids = req.character_ids[:4]

    # Validate realm access (owner or member)
    if req.realm_id is not None:
        realm = db.query(Realm).filter(Realm.id == req.realm_id).first()
        if realm is None:
            raise HTTPException(status_code=404, detail="Realm not found")
        is_owner = realm.owner_id == current_user.id
        is_member = db.query(RealmMembership).filter(
            RealmMembership.realm_id == req.realm_id,
            RealmMembership.user_id == current_user.id,
        ).first() is not None
        if not (is_owner or is_member):
            raise HTTPException(status_code=403, detail="You are not a member of that realm")

    # Validate character ownership
    for char_id in char_ids:
        char = db.query(CharacterModel).filter(
            CharacterModel.id == char_id,
            CharacterModel.owner_id == current_user.id,
        ).first()
        if char is None:
            raise HTTPException(
                status_code=403,
                detail=f"Character {char_id} not found or not owned by you",
            )

    # Fetch character objects for memory seeding
    story_char_dicts: list[dict[str, Any]] = []
    for char_id in char_ids:
        char = db.query(CharacterModel).filter(CharacterModel.id == char_id).first()
        if char:
            entry: dict[str, Any] = {
                "name": char.name or "",
                "role": char.role or "",
                "species": char.species or "",
                "short_bio": char.short_bio or "",
                "tags": char.tags or "",
            }
            if char.identity_spec_json:
                try:
                    spec = (
                        json.loads(char.identity_spec_json)
                        if isinstance(char.identity_spec_json, str)
                        else char.identity_spec_json
                    )
                    if isinstance(spec, dict):
                        for field in ("traits", "personality", "personality_traits"):
                            val = spec.get(field)
                            if val:
                                entry["traits"] = val
                                break
                except Exception:  # noqa: BLE001
                    pass
            story_char_dicts.append(entry)

    # Seed initial canon memory from story creation inputs
    seeded_memory = seed_memory_from_story_creation(
        title=req.title.strip(),
        genre=req.genre or "",
        premise=req.premise or "",
        characters=story_char_dicts,
    )

    now = datetime.utcnow()
    story = StoryModel(
        id=str(uuid.uuid4()),
        user_id=current_user.id,
        title=req.title.strip(),
        genre=req.genre,
        premise=req.premise,
        realm_id=req.realm_id,
        character_ids=char_ids,
        cover_color=req.cover_color or "#1a1a2e",
        created_at=now,
        updated_at=now,
    )
    db.add(story)
    db.commit()
    db.refresh(story)

    # Create StoryState with seeded memory
    initial_state = dict(_DEFAULT_STATE)
    initial_state["memory"] = seeded_memory
    state_row = StoryState(
        story_id=story.id,
        story_summary="",
        state_json=initial_state,
        updated_at=now,
    )
    db.add(state_row)
    db.commit()

    return _story_to_response(story)


